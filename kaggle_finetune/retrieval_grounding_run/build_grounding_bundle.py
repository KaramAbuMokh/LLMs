# Packs the grounding-run modules plus the shared modules of the earlier runs into ONE Kaggle script and writes its PRIVATE notebook metadata
# Modes: grounding_smoke (60 steps on the GPU), grounding_full (the real run), dry_grounding (local CPU crash test: use --push-folder outside the project)
import argparse  # command line options
import json  # metadata file
from pathlib import Path  # file paths

FOLDER = Path(__file__).resolve().parent  # kaggle_finetune/retrieval_grounding_run/
FINETUNE_FOLDER = FOLDER.parent  # kaggle_finetune/
SOURCE_FOLDERS = (FINETUNE_FOLDER / "kernel_source", FINETUNE_FOLDER / "mixed_run/mixed_kernel_source", FOLDER / "grounding_kernel_source")  # shared, mixed, grounding
SKIPPED_FILES = {"run_entry.py", "pair_filters.py", "mixed_entry.py", "mixed_ladder.py", "mixed_evaluation.py", "mixed_training.py", "sanity_ladder.py"}  # entry points and ladders of earlier runs
DEFAULT_PUSH_FOLDER = FOLDER / "kernel_push"  # what `kaggle kernels push` uploads
KERNEL_ID = "karamabumokh/got-gpt2-retrieval-grounding-finetune"  # private notebook name on Kaggle
CODE_FILE = "got_gpt2_retrieval_grounding_finetune.py"  # the generated single file
DATASET_SOURCES = ["karamabumokh/got-gpt2-mixed-books-qa", "karamabumokh/got-gpt2-grounded-examples"]  # both private: plain pairs and books, grounded sequences
KERNEL_SOURCES = ["karamabumokh/got-gpt2-mixed-books-qa-finetune"]  # the mixed notebook: its output model.pth is the model live in the Space
PRELUDE = '''# GENERATED by retrieval_grounding_run/build_grounding_bundle.py (run mode: {mode}). Edit the source folders and rebuild, never this file.
import os  # run mode switch
import subprocess  # pip, only if tiktoken is missing (the only reason internet is on)
import sys  # import path
import tempfile  # where the source files are unpacked
from pathlib import Path  # file paths

os.environ["GOT_GROUNDING_RUN_MODE"] = "{mode}"  # grounding_smoke, grounding_full or dry_grounding
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")  # less GPU memory fragmentation (set before torch loads)
SOURCE_FILES = {sources}  # file name -> source text
try:  # the tokenizer library
    import tiktoken  # already in the Kaggle image?
except ImportError:  # not installed
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "tiktoken"], check=True)  # install it (internet: pip only)
source_folder = Path(tempfile.mkdtemp(prefix="got_grounding_source_"))  # outside /kaggle/working, keeps the output clean
for file_name, source_text in SOURCE_FILES.items():  # every module
    (source_folder / file_name).write_text(source_text, encoding="utf-8")  # write it back as a file
sys.path.insert(0, str(source_folder))  # make the modules importable
import grounding_entry  # noqa: E402  the entry module
grounding_entry.main()  # run the chosen mode
'''


def collect_sources():  # file name -> text for every module the kernel needs
    sources = {}  # result
    for folder in SOURCE_FOLDERS:  # shared, mixed, grounding
        for path in sorted(folder.glob("*.py")):  # every module in the folder
            if path.name in SKIPPED_FILES:  # not needed here
                continue  # skip it
            if path.name in sources:  # two modules with one name would shadow each other
                raise ValueError(f"module name used twice: {path.name}")  # stop the build
            sources[path.name] = path.read_text(encoding="utf-8")  # keep it
    return sources  # all modules


def build_bundle(mode, push_folder):  # writes the script and the metadata
    push_folder.mkdir(parents=True, exist_ok=True)  # create if needed
    sources = collect_sources()  # all modules
    (push_folder / CODE_FILE).write_text(PRELUDE.format(mode=mode, sources=repr(sources)), encoding="utf-8")  # one file
    metadata = {"id": KERNEL_ID, "title": KERNEL_ID.split("/")[1], "code_file": CODE_FILE, "language": "python", "kernel_type": "script", "is_private": True,  # private GPU notebook
                "enable_gpu": True, "enable_tpu": False, "enable_internet": True, "dataset_sources": DATASET_SOURCES, "kernel_sources": KERNEL_SOURCES,
                "competition_sources": [], "model_sources": [], "keywords": [], "machine_shape": "NvidiaTeslaT4"}
    (push_folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=1), encoding="utf-8")  # read by the CLI
    print(f"built {mode} bundle: {push_folder / CODE_FILE} ({len(sources)} modules)")  # confirmation


if __name__ == "__main__":  # run as a script
    parser = argparse.ArgumentParser(description="Build the single-file Kaggle script of the grounding run")  # parser
    parser.add_argument("mode", choices=["grounding_smoke", "grounding_full", "dry_grounding"])  # which run
    parser.add_argument("--push-folder", default=str(DEFAULT_PUSH_FOLDER))  # output folder
    options = parser.parse_args()  # parsed options
    build_bundle(options.mode, Path(options.push_folder))  # do the work
